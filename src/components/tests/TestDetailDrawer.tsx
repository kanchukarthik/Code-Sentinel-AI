import React, { useState } from 'react';
import { SynthesizedTest } from '../../types/testSynthesis';
import { StatusBadge } from '../common/StatusBadge';
import { Modal } from '../common/Modal';
import {
  FileCode,
  Sparkles,
  Dna,
  Clock,
  Copy,
  Check,
  Target,
  ExternalLink,
  Code2,
} from 'lucide-react';

interface TestDetailDrawerProps {
  test: SynthesizedTest | null;
  onClose: () => void;
}

export const TestDetailDrawer: React.FC<TestDetailDrawerProps> = ({ test, onClose }) => {
  const [copied, setCopied] = useState<boolean>(false);

  if (!test) return null;

  const handleCopyCode = () => {
    navigator.clipboard.writeText(test.codeSnippet);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const getCategoryColor = (cat: string) => {
    switch (cat) {
      case 'boundary':
        return 'bg-purple-500/10 text-purple-300 border-purple-500/30';
      case 'negative':
        return 'bg-rose-500/10 text-rose-300 border-rose-500/30';
      case 'regression':
        return 'bg-amber-500/10 text-amber-300 border-amber-500/30';
      case 'exception-handling':
        return 'bg-cyan-500/10 text-cyan-300 border-cyan-500/30';
      default:
        return 'bg-blue-500/10 text-blue-300 border-blue-500/30';
    }
  };

  return (
    <Modal
      isOpen={!!test}
      onClose={onClose}
      title={`Synthesized Test: ${test.name}`}
      subtitle={`Generated by Autonomous Test Synthesis Agent &bull; Key: ${test.testKey}`}
      maxWidth="max-w-4xl"
    >
      <div className="space-y-5 font-mono text-xs">
        {/* Meta Header Grid */}
        <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
          <div className="rounded-xl border border-slate-800 bg-slate-950 p-3">
            <span className="text-[10px] text-slate-500 uppercase block mb-1">Status</span>
            <StatusBadge status={test.status} size="md" />
          </div>

          <div className="rounded-xl border border-slate-800 bg-slate-950 p-3">
            <span className="text-[10px] text-slate-500 uppercase block mb-1">Category</span>
            <span className={`inline-block rounded-full border px-2.5 py-0.5 text-xs capitalize ${getCategoryColor(test.category)}`}>
              {test.category}
            </span>
          </div>

          <div className="rounded-xl border border-slate-800 bg-slate-950 p-3">
            <span className="text-[10px] text-slate-500 uppercase block mb-1">Execution Time</span>
            <span className="text-white font-bold">{test.executionTimeMs} ms</span>
          </div>

          <div className="rounded-xl border border-slate-800 bg-slate-950 p-3">
            <span className="text-[10px] text-slate-500 uppercase block mb-1">Mutation Gain</span>
            <span className="text-emerald-400 font-bold">+{test.mutationImpactPct}%</span>
          </div>
        </div>

        {/* Target Code Location & Path Coverage */}
        <div className="rounded-xl border border-slate-800 bg-slate-950/80 p-4 space-y-2">
          <div className="flex items-center justify-between">
            <span className="text-slate-400 flex items-center gap-1.5 font-sans font-semibold">
              <Target className="h-4 w-4 text-cyan-400" />
              Target Codebase Location:
            </span>
            <span className="text-slate-500 text-[11px]">
              Lines {test.targetLineRange[0]}-{test.targetLineRange[1]}
            </span>
          </div>

          <div className="rounded-lg bg-black/60 p-2.5 border border-slate-800/80 flex items-center justify-between">
            <div className="flex items-center gap-2">
              <FileCode className="h-4 w-4 text-purple-400" />
              <span className="text-slate-200">{test.targetFile}</span>
              <span className="text-slate-500">&gt;</span>
              <span className="text-cyan-300 font-bold">{test.targetFunction}()</span>
            </div>
          </div>

          <div className="pt-1 text-[11px] text-slate-400 font-sans">
            <strong className="text-slate-300">Unexplored Branch Covered:</strong> {test.unexploredPathCoverage}
          </div>
        </div>

        {/* Cognitive Agent Rationale */}
        <div className="rounded-xl border border-slate-800 bg-slate-950/80 p-4 font-sans space-y-1.5">
          <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400 flex items-center gap-2">
            <Sparkles className="h-4 w-4 text-amber-400" />
            Agent Synthesis Rationale
          </h4>
          <p className="text-xs text-slate-300 leading-relaxed font-sans">
            {test.agentRationale}
          </p>
        </div>

        {/* Synthesized Test Code Snippet */}
        <div className="rounded-xl border border-slate-800 bg-[#070b14] overflow-hidden">
          <div className="flex items-center justify-between border-b border-slate-800 bg-slate-900/90 px-4 py-2">
            <div className="flex items-center gap-2 text-slate-300 text-xs">
              <Code2 className="h-4 w-4 text-cyan-400" />
              <span>Synthesized Jest / TypeScript Test Case</span>
            </div>
            <button
              onClick={handleCopyCode}
              className="inline-flex items-center gap-1 rounded border border-slate-700 bg-slate-800 px-2 py-1 text-[11px] text-slate-300 hover:bg-slate-700 transition-colors"
            >
              {copied ? (
                <>
                  <Check className="h-3 w-3 text-emerald-400" />
                  <span className="text-emerald-400">Copied</span>
                </>
              ) : (
                <>
                  <Copy className="h-3 w-3 text-slate-400" />
                  <span>Copy Test Code</span>
                </>
              )}
            </button>
          </div>

          <pre className="p-4 text-[12px] text-slate-200 overflow-x-auto leading-relaxed bg-[#060910]">
            <code>{test.codeSnippet}</code>
          </pre>
        </div>
      </div>
    </Modal>
  );
};
